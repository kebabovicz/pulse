export type Lang = 'ru' | 'en'

export const lang: Lang = (localStorage.getItem('pulse.lang') as Lang) ?? 'en'

export function setLang(next: Lang): void {
  localStorage.setItem('pulse.lang', next)
  location.reload()
}

const dict = lang === 'ru' ? ru : en

/** Picks a plural form: Russian has one/few/many, English collapses to one/other. */
function pluralIndex(count: number): 0 | 1 | 2 {
  if (lang !== 'ru') return count === 1 ? 0 : 2
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return 0
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1
  return 2
}

const PLURAL = /\{(\d+)\|([^{}|]*)\|([^{}|]*)\|([^{}|]*)\}/g

export function t(key: keyof typeof en, ...args: (string | number)[]): string {
  let s: string = dict[key]
  s = s.replace(
    PLURAL,
    (_, index: string, one: string, few: string, many: string) =>
      [one, few, many][pluralIndex(Number(args[Number(index)]) || 0)],
  )
  args.forEach((a, i) => {
    s = s.replaceAll(`{${i}}`, String(a))
  })
  return s
}

